#!/usr/bin/env node
// The response headers, written into the artefact — §13.1, §13.2.
//
// Generated rather than hand-written for one reason: the content policy has to name the
// hash of anything that stayed inline, and a hash changes whenever its content does. A
// hand-written policy is a policy that is right until the next build.
//
// It is written to dist/ and NOT served as an asset: the host parses it and applies its
// rules to the responses (public/.assetsignore keeps it out of the asset store).
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;

/** Every .html in the artefact, so nothing inline escapes the scan. */
async function pages(directory) {
    const found = [];

    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const path = join(directory, entry.name);

        if (entry.isDirectory()) {
            found.push(...(await pages(path)));
        } else if (entry.name.endsWith('.html')) {
            found.push(path);
        }
    }

    return found;
}

/**
 * §13.2 — ANYTHING THAT STAYS INLINE IS COVERED BY A HASH NAMED IN THE POLICY, recomputed
 * at every build because it changes at every build.
 *
 * Today nothing is inline: the site emits stylesheets and scripts as files, and
 * verify-output.sh refuses an artefact where one appears uncovered. So these sets come back
 * empty and the policy is hash-free — which is the state to keep. They exist so that the day
 * something has to be inlined, the policy follows it instead of being quietly widened with
 * 'unsafe-inline', which would disable the protection for every script or style on the site
 * to save one request.
 */
async function inlineHashes(files) {
    const scripts = new Set();
    const styles = new Set();

    for (const file of files) {
        const html = await readFile(file, 'utf8');

        for (const [, body] of html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
            if (body.trim() !== '') {
                scripts.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
            }
        }

        for (const [, body] of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) {
            if (body.trim() !== '') {
                styles.add(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
            }
        }
    }

    return { scripts: [...scripts], styles: [...styles] };
}

const found = await pages(dist);

if (found.length === 0) {
    console.error('generate-headers: no page in dist/. Build first.');
    process.exit(1);
}

const { scripts, styles } = await inlineHashes(found);

/**
 * THE NARROW ALLOWANCE, AND ONLY IT — §13.2.
 *
 * A policy that forbids every dynamic evaluation makes the playground impossible: a
 * WebAssembly runtime cannot start without permission to instantiate a module. The engine's
 * loader calls WebAssembly.compileStreaming and instantiateStreaming, and 'wasm-unsafe-eval'
 * is exactly the permission for that and for nothing else — no string eval, no Function
 * construction, no inline script.
 *
 * 'unsafe-eval', the broad one, stays FORBIDDEN. The runtime does carry a `new Function`
 * call, in the path that serves the debugging proxy's callFunctionOn — it never runs on a
 * published site, and the browser check is what settles that rather than this comment.
 */
const policy = [
    "default-src 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
    "img-src 'self' data:",
    "font-src 'self'",
    `style-src 'self'${styles.length > 0 ? ` ${styles.join(' ')}` : ''}`,
    `script-src 'self' 'wasm-unsafe-eval'${scripts.length > 0 ? ` ${scripts.join(' ')}` : ''}`,
    "connect-src 'self'",
    "worker-src 'self'",
    "manifest-src 'self'",
    'upgrade-insecure-requests',
].join('; ');

/**
 * §13.1 — strict transport ONCE THE DOMAIN IS VALIDATED, and not before. Sending it from a
 * deployment whose custom domain is not yet serving is how a site locks its own visitors
 * out for the lifetime of the max-age. So it is opt-in, and the deployment that turns it on
 * is the one that has checked.
 */
const hsts = process.env.PUBLIC_HSTS === 'on';

const headers = `# Generated by scripts/generate-headers.mjs — do not edit.
#
# Parsed by the host and applied to responses; never served as an asset
# (see public/.assetsignore). The content policy below names the hash of anything that
# stayed inline, which is why this file is generated at every build.

/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()
  Content-Security-Policy: ${policy}
${hsts ? '  Strict-Transport-Security: max-age=31536000; includeSubDomains\n' : ''}  Cache-Control: no-cache

# Fingerprinted by the bundler: the name changes when the bytes do, so these never go stale.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable

# The playground's runtime. Its names are STABLE and cannot be fingerprinted — the map from
# logical to fingerprinted name is written outside the served directory, so a static host
# can never read it (§13.1). Cached by path, therefore, and revalidated: a visitor holding
# last release's runtime must not be served it after a deployment. The round trip is the
# price of that, and §12.5 is where the real deployment settles whether it is the right
# trade.
/playground/_framework/*
  Cache-Control: no-cache

# Says which release is live. Never cached, or it answers for the previous one.
/version.json
  Cache-Control: no-store
`;

await writeFile(join(dist, '_headers'), headers, 'utf8');

console.log(
    `generate-headers: ${found.length} pages scanned, ` +
    `${scripts.length} inline scripts and ${styles.length} inline styles hashed` +
    `${hsts ? ', strict transport ON' : ''}.`,
);
